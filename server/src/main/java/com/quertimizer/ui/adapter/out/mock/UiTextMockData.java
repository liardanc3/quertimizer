    private final UiTextRepositoryPort uiTextRepository;

    @PostConstruct
    public void seed() {
        // 기본 UI 텍스트 Mock 데이터 적재
        List<UiText> uiTexts = new ArrayList<>();
        uiTexts.addAll(toUiTexts(KR_UI_TEXTS, KOREAN_LANGUAGE));
        uiTexts.addAll(toUiTexts(DEFAULT_UI_TEXTS, UiTextLanguage.DEFAULT.getValue()));
        uiTextRepository.saveAll(uiTexts);
    }

    private List<UiText> toUiTexts(List<UiTextSeed> seeds, String language) {
        return seeds.stream()
                .map(seed -> UiText.create(seed.key(), seed.value(), language, seed.description()))
                .toList();
    }

    private static final class UiTextSeed {

        private final String key;
        private final String value;
        private final String description;

        private UiTextSeed(String key, String value, String description) {
            this.key = key;
            this.value = value;
            this.description = description;
        }

        private String key() {
            return key;
        }

        private String value() {
            return value;
        }

        private String description() {
            return description;
        }
    }

